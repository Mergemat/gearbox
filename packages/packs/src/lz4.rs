pub const MAX_BLOCK: usize = 4128;
pub const BLOCK_OUT: usize = 4096;

#[derive(Clone)]
pub struct Decoder {
    pub buf: Vec<u8>,
}

impl Default for Decoder {
    fn default() -> Self {
        Self::new()
    }
}

impl Decoder {
    pub fn new() -> Self {
        Decoder { buf: DICTIONARY.to_vec() }
    }

    pub fn output(&self) -> &[u8] {
        &self.buf[DICTIONARY.len()..]
    }

    pub fn out_len(&self) -> usize {
        self.buf.len() - DICTIONARY.len()
    }

    pub fn block(&mut self, src: &[u8]) -> Result<usize> {
        let start = self.buf.len();
        match self.block_inner(src) {
            Ok(()) => Ok(self.buf.len() - start),
            Err(e) => {
                self.buf.truncate(start);
                Err(e)
            }
        }
    }

    fn block_inner(&mut self, src: &[u8]) -> Result<()> {
        let start = self.buf.len();
        let limit = start + BLOCK_OUT;
        let mut i = 0;
        loop {
            ensure!(i < src.len(), "lz4: truncated token");
            let token = src[i];
            i += 1;
            let mut lit = (token >> 4) as usize;
            if lit == 15 {
                loop {
                    ensure!(i < src.len(), "lz4: truncated literal length");
                    let b = src[i];
                    i += 1;
                    lit += b as usize;
                    if b != 255 {
                        break;
                    }
                }
            }
            ensure!(i + lit <= src.len(), "lz4: literals past end");
            ensure!(self.buf.len() + lit <= limit, "lz4: output overflow");
            self.buf.extend_from_slice(&src[i..i + lit]);
            i += lit;
            if i == src.len() {
                return Ok(());
            }
            ensure!(i + 2 <= src.len(), "lz4: truncated offset");
            let off = u16::from_le_bytes([src[i], src[i + 1]]) as usize;
            i += 2;
            ensure!(off != 0 && off <= self.buf.len(), "lz4: bad offset {off}");
            let mut ml = (token & 15) as usize;
            if ml == 15 {
                loop {
                    ensure!(i < src.len(), "lz4: truncated match length");
                    let b = src[i];
                    i += 1;
                    ml += b as usize;
                    if b != 255 {
                        break;
                    }
                }
            }
            ml += 4;
            if self.buf.len() + ml > limit {
                bail!("lz4: output overflow");
            }
            let from = self.buf.len() - off;
            for k in 0..ml {
                let b = self.buf[from + k];
                self.buf.push(b);
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matches_reach_into_the_dictionary_and_output() {
        let mut d = Decoder::new();
        let block = [0x00, 6, 0, 0x22, b'A', b'B', 2, 0, 0x10, b'Z'];
        let n = d.block(&block).unwrap();
        assert_eq!(
            d.output(),
            &[0x80, 0x3f, 0xff, 0xff, b'A', b'B', b'A', b'B', b'A', b'B', b'A', b'B', b'Z']
        );
        assert_eq!(n, 13);
    }

    #[test]
    fn bad_offsets_leave_the_state_unchanged() {
        let mut d = Decoder::new();
        d.block(&[0x10, b'x']).unwrap();
        let before = d.buf.len();
        assert!(d.block(&[0x00, 0xff, 0xff, 0x10, b'y']).is_err());
        assert_eq!(d.buf.len(), before);
    }
}
