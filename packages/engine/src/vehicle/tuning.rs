#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CarModelKind {
    Legacy(u32),
    Sport,
    Other(u32),
}

impl CarModelKind {
    pub fn from_code(code: u32) -> Self {
        match code {
            0..=2 => Self::Legacy(code),
            5 => Self::Sport,
            _ => Self::Other(code),
        }
    }

    pub fn uses_legacy_gearbox(self) -> bool {
        match self {
            Self::Legacy(_) => true,
            Self::Sport => false,
            Self::Other(code) => (code as i32) < 5,
        }
    }

    pub fn updates_wheel_visuals(self) -> bool {
        matches!(self, Self::Legacy(_) | Self::Sport | Self::Other(3 | 4))
    }

    pub fn uses_legacy_drive_thrust(self) -> bool {
        matches!(self, Self::Legacy(1))
    }

    pub fn uses_water_angular_hold(self) -> bool {
        matches!(self, Self::Sport | Self::Other(4))
    }

    pub fn uses_legacy_contact_drag(self) -> bool {
        match self {
            Self::Legacy(_) => true,
            Self::Sport => false,
            Self::Other(code) => (code as i32) < 4,
        }
    }

    pub fn clears_hover_suspension(self) -> bool {
        match self {
            Self::Legacy(_) => true,
            Self::Sport => false,
            Self::Other(code) => (code as i32) <= 2,
        }
    }

    pub fn uses_primary_forward(self) -> bool {
        match self {
            Self::Legacy(_) | Self::Sport => true,
            Self::Other(code) => (code as i32) < 6,
        }
    }
}

impl Tuning {
    pub fn car_model_kind(&self) -> CarModelKind {
        CarModelKind::from_code(self.model_kind)
    }
}

