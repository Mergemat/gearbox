const fn tables() -> ([u32; 24], [[u8; 24]; 24]) {
    let mut masks = [0; 24];
    let mut pairs = [[0; 24]; 24];
    let mut index = 0;
    while index < REGISTRATIONS.len() {
        let (a, b, collide, ab, ba) = REGISTRATIONS[index];
        pairs[a][b] = collide | ab << 1 | ba << 2 | 8;
        pairs[b][a] = collide | ba << 1 | ab << 2 | 8;
        masks[a] |= 1 << (b - 1);
        masks[b] |= 1 << (a - 1);
        index += 1;
    }
    (masks, pairs)
}

